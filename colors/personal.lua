local tint =
   { Error = p.error_bg, Warn = p.warn_bg, Info = p.info_bg, Hint = p.hint_bg, Ok = p.hint_bg }
for kind, color in pairs({
   Error = p.error,
   Warn = p.warn,
   Info = p.info,
   Hint = p.hint,
   Ok = p.green,
}) do
   hi("DiagnosticVirtualText" .. kind, { fg = color, bg = tint[kind] })
   hi("Diagnostic" .. kind, { fg = color })
   hi("DiagnosticUnderline" .. kind, { sp = color, underline = true })
   for _, suffix in ipairs({ "Sign", "Floating", "VirtualLines" }) do
      link("Diagnostic" .. suffix .. kind, "Diagnostic" .. kind)
   end
end

